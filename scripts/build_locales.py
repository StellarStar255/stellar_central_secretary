"""Share one translation catalogue between the UI, native menus and offline tutorial."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
static=ROOT/'secretary/static'
messages=json.loads((static/'locales.json').read_text(encoding='utf-8'))
(static/'i18n-data.js').write_text('/* Generated by scripts/build_locales.py */\nglobalThis.StellarTranslations='+json.dumps(messages,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print('Built i18n-data.js:',len(messages),'translations')
